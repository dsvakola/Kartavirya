/** An icon as an HTML string. `name` must be one of the keys above. */
export function icon(name) {
  const body = P[name] || P.tag;
  return `<span class="ico" aria-hidden="true"><svg viewBox="0 0 24 24" focusable="false">${body}</svg></span>`;
}

/** Fills every `<span data-icon="name">` inside `root`. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.dataset.iconDone === el.dataset.icon) return;
    const body = P[el.dataset.icon] || P.tag;
    el.classList.add("ico");
    el.setAttribute("aria-hidden", "true");
    el.innerHTML = `<svg viewBox="0 0 24 24" focusable="false">${body}</svg>`;
    el.dataset.iconDone = el.dataset.icon;
  });
}
